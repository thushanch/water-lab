#!/usr/bin/env python3
"""Write the IMGS manifest into water-lab.html between its marker comments.

Only images that actually exist in img/ are listed, so a missing or held-back
image never produces a broken figure. Run after adding or removing images:

    python3 image-prompts/_build/inject_manifest.py
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from data_sims import SIMS, MODULES
from data_site import COVERS, SITE

ROOT = os.path.dirname(os.path.dirname(HERE))
IMG = os.path.join(ROOT, 'img')
HTML = os.path.join(ROOT, 'water-lab.html')
BEGIN, END = '/* IMGS:BEGIN generated by image-prompts/_build/inject_manifest.py, do not hand-edit */', '/* IMGS:END */'

def has(name):
    return os.path.isfile(os.path.join(IMG, name))

def split_labels(txt, fam):
    if fam == 'C':
        i = txt.find(' Right:')
        if i < 0: return [txt]
        l, r = txt[:i].strip().rstrip('.'), txt[i:].strip().rstrip('.')
        return [re.sub(r'^Left:\s*', '', l), re.sub(r'^Right:\s*', '', r)]
    out = []
    for chunk in txt.split('. '):
        chunk = chunk.strip().rstrip('.')
        if not chunk: continue
        if ':' in chunk: out.append(chunk)
        else: out += [c.strip() for c in chunk.split(', ') if c.strip()]
    return [o[0].upper() + o[1:] for o in out]

def cap1(s):
    return s[0].upper() + s[1:] if s else s

M = {'sim': {}, 'mod': {}, 'site': {}}
for s in SIMS:
    e = {}
    for fam, suf in (('A', 'field'), ('B', 'concept'), ('C', 'trap')):
        if fam in s and has(f"{s['k']}-{suf}.webp"):
            d = {'alt': s[fam]['alt'], 'cap': s[fam]['cap']}
            if fam in 'BC':
                lab = split_labels(s[fam]['labels'], fam)
                d['labels'] = [cap1(x) for x in lab]
            e[suf] = d
    if e: M['sim'][s['k']] = e
for n, _, _ in MODULES:
    if has(f"m{n}-cover.webp"):
        M['mod'][n] = {'alt': COVERS[n]['alt']}
for s in SITE:
    fn = s['file'].split(' ')[0].replace('img/', '')
    if has(fn):
        M['site'][s['id']] = {'alt': s['alt']}

js = BEGIN + '\nconst IMGS=' + json.dumps(M, ensure_ascii=False, separators=(',', ':')) + ';\n' + END
src = open(HTML, encoding='utf-8').read()
if BEGIN in src:
    pre, rest = src.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    src = pre + js + post
else:
    anchor = 'const CATALOG=['
    assert anchor in src
    src = src.replace(anchor, js + '\n\n' + anchor, 1)
open(HTML, 'w', encoding='utf-8').write(src)
n = sum(len(v) for v in M['sim'].values()) + len(M['mod']) + len(M['site'])
print(f"IMGS manifest: {n} images ({len(M['sim'])} sims, {len(M['mod'])} covers, {len(M['site'])} site), {len(js)//1024} kB")
